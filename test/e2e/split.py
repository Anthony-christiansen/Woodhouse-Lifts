import os
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.abspath(os.path.join(HERE,'..','..'))
os.makedirs(HERE+'/shots', exist_ok=True)
import asyncio, subprocess, sys
from playwright.async_api import async_playwright
srv=subprocess.Popen([sys.executable,'-m','http.server','8775','-d',ROOT],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
MOCK=open(HERE+'/mock-supabase.js').read(); B='http://localhost:8775/'
R=[]
def ok(n,c,x=''): R.append(('PASS' if c else 'FAIL',n,x))
async def main():
    async with async_playwright() as p:
        br=await p.chromium.launch(args=['--no-sandbox'])
        ctx=await br.new_context(viewport={'width':360,'height':900},is_mobile=True,has_touch=True,device_scale_factor=2)
        await ctx.route('https://cdn.jsdelivr.net/**', lambda r: r.fulfill(status=200, content_type='application/javascript', body=MOCK))
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(B+'#/new'); await pg.wait_for_timeout(700)
        n=await pg.evaluate("document.querySelectorAll('[data-goal]').length"); ok('3 goal tiles', n==3, n)
        await pg.click('[data-goal="hypertrophy"]')
        await pg.select_option('#days','6'); await pg.wait_for_timeout(150)
        sp=await pg.evaluate("[...document.querySelectorAll('[data-split]')].map(b=>b.dataset.split+(b.getAttribute('aria-pressed')=='true'?'*':''))")
        ok('6 days offers full-body split (rec) + PPL', 'full_body_split*' in sp and 'ppl' in sp, sp)
        await pg.click('[data-split="ppl"]'); await pg.wait_for_timeout(100)
        await pg.screenshot(path=HERE+'/shots/builder_split.png', full_page=True)
        await pg.fill('#name','T'); await pg.click('#next'); await pg.wait_for_timeout(400)
        labels=await pg.evaluate("[...document.querySelectorAll('[data-label]')].map(i=>i.value)")
        ok('PPL day labels', labels[:3]==['Push','Pull','Legs'], labels)
        t=await pg.inner_text('main'); ok('header shows split', 'Step 2 of 2' in t and 'Push / Pull / Legs' in t)
        await pg.close(); pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e))); await pg.goto(B+'#/new'); await pg.wait_for_timeout(500)
        await pg.select_option('#days','3'); await pg.wait_for_timeout(100)
        await pg.click('[data-split="full_body"]'); await pg.fill('#name','T'); await pg.click('#next'); await pg.wait_for_timeout(400)
        labels=await pg.evaluate("[...document.querySelectorAll('[data-label]')].map(i=>i.value)")
        ok('full body labels', all('Full' in l for l in labels) and len(labels)==3, labels)
        await pg.goto(B+'#/workout/d21'); await pg.wait_for_timeout(800)
        w=pg.locator('[data-f="weight"]').first; v=await w.input_value()
        await w.fill(str(round(float(v or 100)*10))); await w.dispatch_event('change'); await pg.wait_for_timeout(200)
        cls=await w.get_attribute('class'); toast=await pg.evaluate("[...document.querySelectorAll('.toast')].map(x=>x.innerText).join('|')")
        ok('typo guard flags 10x weight', 'odd' in (cls or '') and 'typo' in toast, (v,cls,toast))
        await w.fill(str(round(float(v or 100)*1.25))); await w.dispatch_event('change'); await pg.wait_for_timeout(200)
        t2=await pg.evaluate("[...document.querySelectorAll('.toast')].map(x=>x.innerText).join('|')")
        ok('big-jump warning at +25%', 'Manual bump' in t2 and 'injury' in t2, t2)
        ok('no JS errors', not errs, errs)
        await br.close()
    srv.terminate()
    for r in R: print(*r)
    print('SPLIT UI TESTS:', 'ALL PASSED' if all(r[0]=='PASS' for r in R) else 'FAILURES')
asyncio.run(main())
